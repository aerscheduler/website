#!/usr/bin/env node
/**
 * Guards for the AI-readable outputs (`/llms.txt`, `/llms-full.txt`, and the
 * `/docs/<section>/<slug>.md` twin of every help article). See `src/lib/llms.ts`.
 *
 * Two modes, both in the build command:
 *
 *   node scripts/check-llms.mjs          before `next build`, about a second
 *     - every help article MDX converts to clean Markdown (fails on an unknown
 *       component, a bad prop, an expression, an import, a leftover tag, or a
 *       banned dash), with screenshots resolved against the real registry
 *     - every component `src/mdx-components.tsx` injects has a Markdown mapping
 *
 *   node scripts/check-llms.mjs --built  after `next build`, reading `.next`
 *     - every prerendered help article has a prerendered Markdown twin
 *     - llms.txt lists every feature, comparison, docs section and article
 *     - every aerscheduler.com link in llms.txt resolves to a real route or file
 *     - the price and trial length stated match `src/lib/site.ts`
 *     - no rendering artifacts, and both files stay under their size caps
 *     - the `.md` rewrite really maps each article path, and not the HTML path
 *
 * Why after the build: the outputs are generated by the same registries the
 * pages render from, so the only way to prove nothing was left out is to read
 * what will actually ship.
 */
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_URL = "https://www.aerscheduler.com";
const built = process.argv.includes("--built");
const failures = [];
const fail = (msg) => failures.push(msg);

const { mdxToMarkdown, assertCleanMarkdown, HANDLED_COMPONENTS } = await import(
  pathToFileURL(path.join(root, "src/lib/mdx-markdown.mjs")).href
);

/** A numeric constant from src/lib/site.ts, read as text (the file is TypeScript). */
function siteConstant(name) {
  const m = readFileSync(path.join(root, "src/lib/site.ts"), "utf8").match(new RegExp(`export const ${name}\\s*=\\s*(\\d+)`));
  if (!m) throw new Error(`check-llms: could not read ${name} from src/lib/site.ts`);
  return Number(m[1]);
}

if (!built) {
  /* ---------------- before the build ---------------- */

  // Screenshot registry, read the way scripts/check-docs.mjs reads it.
  const shotsSource = readFileSync(path.join(root, "src/lib/docs-screenshots.ts"), "utf8");
  const shotIds = new Set([...shotsSource.matchAll(/^\s{4}id:\s*"([^"]+)"/gm)].map((m) => m[1]));
  const resolveScreenshot = (id) => {
    if (!shotIds.has(id)) return undefined;
    return existsSync(path.join(root, "public/docs", `${id}.png`)) ? { alt: "alt", src: `/docs/${id}.png` } : null;
  };

  const docsDir = path.join(root, "src/content/docs");
  let converted = 0;
  for (const entry of readdirSync(docsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue; // a stray .DS_Store is not a section
    const section = entry.name;
    const dir = path.join(docsDir, section);
    for (const name of readdirSync(dir).filter((f) => f.endsWith(".mdx"))) {
      const file = `src/content/docs/${section}/${name}`;
      try {
        const md = mdxToMarkdown(readFileSync(path.join(dir, name), "utf8"), {
          file,
          pageUrl: `${SITE_URL}/docs/${section}/${name.replace(/\.mdx$/, "")}`,
          siteUrl: SITE_URL,
          resolveScreenshot,
        });
        assertCleanMarkdown(md, file);
        converted++;
      } catch (error) {
        fail(error.message);
      }
    }
  }

  // Every component the MDX loader injects must have a Markdown mapping, so a new
  // one fails here before any article uses it.
  const mdxComponents = readFileSync(path.join(root, "src/mdx-components.tsx"), "utf8");
  const returned = mdxComponents.match(/return\s*\{([\s\S]*?)\};/);
  if (!returned) fail("check-llms: could not read the components useMDXComponents returns");
  // Every entry of the object, however it is written: `Where`, `Where,Tabs`, `Tabs: DocTabs`, `...more`.
  const entries = (returned?.[1] ?? "")
    .replace(/\/\/.*$/gm, "")
    .split(/[,\n]/)
    .map((t) => t.trim())
    .filter(Boolean);
  const injected = [];
  for (const entry of entries) {
    if (entry.startsWith("...")) {
      // The prose (lower-case HTML element) overrides and the caller's own map are the only spreads allowed.
      if (!["...proseComponents", "...components"].includes(entry)) fail(`src/mdx-components.tsx spreads ${entry}; give its components Markdown mappings and allow the spread in scripts/check-llms.mjs`);
      continue;
    }
    const name = entry.split(":")[0].trim();
    if (/^[A-Z]/.test(name)) injected.push(name);
  }
  for (const name of injected) {
    if (!HANDLED_COMPONENTS.includes(name)) {
      fail(`src/mdx-components.tsx injects <${name}>, which has no Markdown mapping in src/lib/mdx-markdown.mjs`);
    }
  }
  if (!injected.length) fail("check-llms: found no components in useMDXComponents; the parser here is blind");

  report(`${converted} help articles convert to clean Markdown; ${injected.length} components mapped`);
} else {
  /* ---------------- after the build ---------------- */

  const appDir = path.join(root, ".next/server/app");
  const manifestPath = path.join(root, ".next/prerender-manifest.json");
  if (!existsSync(manifestPath)) {
    fail("check-llms --built: .next/prerender-manifest.json is missing; run after `next build`");
    report("");
  }
  const routes = new Set(Object.keys(JSON.parse(readFileSync(manifestPath, "utf8")).routes));
  const body = (route) => {
    const file = path.join(appDir, `${route}.body`);
    return existsSync(file) ? readFileSync(file, "utf8") : null;
  };

  const llms = body("/llms.txt");
  const full = body("/llms-full.txt");
  if (!llms) fail("/llms.txt was not prerendered");
  if (!full) fail("/llms-full.txt was not prerendered");

  const docArticles = [...routes].filter((r) => /^\/docs\/(?!api\/)[a-z0-9-]+\/[a-z0-9-]+$/.test(r));
  const docSections = [...routes].filter((r) => /^\/docs\/(?!api$)[a-z0-9-]+$/.test(r));
  const features = [...routes].filter((r) => /^\/features\/[a-z0-9-]+$/.test(r));
  const comparisons = [...routes].filter((r) => /^\/compare\/[a-z0-9-]+$/.test(r));
  const apiTags = [...routes].filter((r) => /^\/docs\/api(\/[a-z0-9-]+)?$/.test(r));
  if (docArticles.length < 100) fail(`only ${docArticles.length} help articles prerendered; the route pattern here is blind`);

  // Every article has a Markdown twin, and it starts with its title.
  for (const r of docArticles) {
    const md = body(`/md${r}`);
    if (!md) fail(`${r} has no prerendered Markdown twin at /md${r}`);
    else if (!md.startsWith("# ")) fail(`/md${r} does not start with an H1 title`);
  }

  // The regulations library: every section and Part page has a Markdown twin,
  // and llms.txt lists every section's twin.
  const regPages = [...routes].filter((r) => /^\/regulations\/[a-z0-9-]+$/.test(r));
  const regSections = regPages.filter((r) => !/\/part-\d+$/.test(r));
  if (regSections.length < 40) fail(`only ${regSections.length} regulation pages prerendered; the route pattern here is blind`);
  for (const r of [...regPages, "/regulations"]) {
    const md = body(`/md${r}`);
    if (!md) fail(`${r} has no prerendered Markdown twin at /md${r}`);
    else if (!md.startsWith("# ")) fail(`/md${r} does not start with an H1 title`);
  }
  if (llms) for (const r of regSections) if (!llms.includes(`(${SITE_URL}${r}.md)`)) fail(`/llms.txt does not list ${r}.md`);

  // Every Markdown twin, for the checks that run over all outputs.
  const mdBodies = [...docArticles, ...regPages, "/regulations"].map((r) => [`/md${r}`, body(`/md${r}`)]).filter(([, t]) => t);
  const outputs = [["/llms.txt", llms], ["/llms-full.txt", full], ...mdBodies].filter(([, t]) => t);

  if (llms) {
    // Everything that exists is listed.
    for (const r of [...features, ...comparisons, ...docSections, ...apiTags]) {
      if (!llms.includes(`(${SITE_URL}${r})`)) fail(`/llms.txt does not list ${r}`);
    }
    for (const r of docArticles) {
      if (!llms.includes(`(${SITE_URL}${r}.md)`)) fail(`/llms.txt does not list ${r}.md`);
    }
    const price = siteConstant("PRICE_PER_AIRCRAFT");
    const trial = siteConstant("TRIAL_DAYS");
    if (!llms.includes(`$${price} per aircraft per month`)) fail(`/llms.txt does not state the price as $${price} per aircraft per month`);
    if (!llms.includes(`Free trial: ${trial} days`)) fail(`/llms.txt does not state the trial as ${trial} days`);
  }

  // Every link on our own domain, in every output, resolves to something that ships.
  for (const [label, text] of outputs) {
    for (const [, url] of text.matchAll(/\]\((https:\/\/www\.aerscheduler\.com[^)\s]*)\)/g)) {
      const p = url.slice(SITE_URL.length).replace(/[#?].*$/, "") || "/";
      const mdTwin = p.endsWith(".md") ? `/md${p.slice(0, -3)}` : null;
      const ok = p === "/" || routes.has(p) || (mdTwin && routes.has(mdTwin)) || existsSync(path.join(root, "public", p));
      if (!ok) fail(`${label} links to ${url}, which is not a prerendered route or a public file`);
    }
  }

  // Every price per aircraft and every trial length stated, in every output, matches the
  // constants, except in a line about a named competitor (Flight Circle publishes $10).
  {
    const price = siteConstant("PRICE_PER_AIRCRAFT");
    const trial = siteConstant("TRIAL_DAYS");
    const rivals = [...(llms ?? "").matchAll(/\[AerScheduler vs ([^\]]+)\]/g)].map((m) => m[1]);
    if (llms && rivals.length < 3) fail("check-llms: could not read the competitor names from /llms.txt; the price check is blind");
    const PRICE = /\$\s?(\d+)(?:\.00)?\s*(?:\/\s*mo(?:nth)?|a month|per month)?\s*(?:per|\/|an?)\s*aircraft/gi;
    const TRIAL = /(\d+)[- ]day (?:free )?trial|trial (?:is|of|lasts|runs) (\d+) days|(\d+) days free/gi;
    for (const [label, text] of outputs) {
      for (const raw of text.split("\n")) {
        // A comparison table row is "| Topic | AerScheduler | Them |": only our cell is ours to check.
        const line = raw.startsWith("|") ? (raw.split("|")[2] ?? "") : raw;
        if (rivals.some((r) => line.includes(r))) continue;
        for (const m of line.matchAll(PRICE)) {
          if (Number(m[1]) !== price) fail(`${label} states "${m[0]}"; PRICE_PER_AIRCRAFT is ${price}: "${line.trim().slice(0, 120)}"`);
        }
        for (const m of line.matchAll(TRIAL)) {
          const n = Number(m[1] ?? m[2] ?? m[3]);
          if (n !== trial) fail(`${label} states a ${n}-day trial; TRIAL_DAYS is ${trial}: "${line.trim().slice(0, 120)}"`);
        }
      }
    }
  }

  // No artifacts, and sizes stay sane.
  for (const [label, text] of outputs) {
    if (/\bundefined\b|\[object Object\]|\bNaN\b|\$\{/.test(text)) fail(`${label} contains a rendering artifact`);
  }
  for (const [label, text, cap] of [["/llms.txt", llms, 150_000], ["/llms-full.txt", full, 2_000_000]]) {
    const bytes = text ? Buffer.byteLength(text, "utf8") : 0;
    if (bytes > cap) fail(`${label} is ${bytes} bytes, over its ${cap}-byte cap`);
  }

  // Content types were recorded with the prerendered files.
  for (const [route, type] of [
    ["/llms.txt", "text/plain"],
    ["/llms-full.txt", "text/plain"],
    ...[...docArticles, ...regPages, "/regulations"].map((r) => [`/md${r}`, "text/markdown"]),
  ]) {
    const meta = path.join(appDir, `${route}.meta`);
    if (!existsSync(meta)) { fail(`${route} has no .meta file`); continue; }
    const headers = JSON.parse(readFileSync(meta, "utf8")).headers ?? {};
    if (!String(headers["content-type"] ?? "").startsWith(type)) fail(`${route} is served as ${headers["content-type"]}, expected ${type}`);
  }

  // The rewrite maps every article's .md path to its twin, and leaves the HTML path alone.
  const rm = JSON.parse(readFileSync(path.join(root, ".next/routes-manifest.json"), "utf8"));
  const before = rm.rewrites?.beforeFiles ?? [];
  const rule = before.find((r) => r.destination === "/md/docs/:section/:slug");
  if (!rule) fail("next.config.ts has no beforeFiles rewrite to /md/docs/:section/:slug");
  else {
    const re = new RegExp(rule.regex);
    for (const r of docArticles) {
      if (!re.test(`${r}.md`)) fail(`the .md rewrite does not match ${r}.md`);
      if (re.test(r)) fail(`the .md rewrite also matches the HTML path ${r}`);
    }
  }

  const regRule = before.find((r) => r.destination === "/md/regulations/:slug");
  if (!regRule) fail("next.config.ts has no beforeFiles rewrite to /md/regulations/:slug");
  else {
    const re = new RegExp(regRule.regex);
    for (const r of regPages) {
      if (!re.test(`${r}.md`)) fail(`the regulations .md rewrite does not match ${r}.md`);
      if (re.test(r)) fail(`the regulations .md rewrite also matches the HTML path ${r}`);
    }
  }

  report(
    `${docArticles.length} articles and ${regPages.length} regulation pages with Markdown twins; llms.txt ${Math.round((llms?.length ?? 0) / 1024)} KB, llms-full.txt ${Math.round((full?.length ?? 0) / 1024)} KB`
  );
}

function report(ok) {
  if (failures.length) {
    console.error(`check-llms${built ? " --built" : ""}: ${failures.length} problem(s)\n`);
    for (const f of failures.slice(0, 60)) console.error(`  - ${f}`);
    if (failures.length > 60) console.error(`  ... and ${failures.length - 60} more`);
    process.exit(1);
  }
  console.log(`check-llms${built ? " --built" : ""}: ok. ${ok}`);
  process.exit(0);
}
